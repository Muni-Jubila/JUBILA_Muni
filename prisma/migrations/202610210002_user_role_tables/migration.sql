-- Separa los roles por sistema y migra el rol general existente.
-- El acceso a cada aplicación continúa indicado por JUBILA/RETENCIONES.

CREATE TABLE IF NOT EXISTS "Rol_Jubila" (
  "ID_ROL_JUBILA" SERIAL PRIMARY KEY,
  "NOMBRE_ROL" VARCHAR(32) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS "Rol_Retenciones" (
  "ID_ROL_RETENCIONES" SERIAL PRIMARY KEY,
  "NOMBRE_ROL" VARCHAR(32) NOT NULL UNIQUE
);

INSERT INTO "Rol_Jubila" ("NOMBRE_ROL") VALUES ('ADMIN'), ('JUBILA')
ON CONFLICT ("NOMBRE_ROL") DO NOTHING;
INSERT INTO "Rol_Retenciones" ("NOMBRE_ROL") VALUES ('Administrador'), ('Retenciones')
ON CONFLICT ("NOMBRE_ROL") DO NOTHING;

ALTER TABLE "USUARIO"
  ADD COLUMN IF NOT EXISTS "ID_ROL_JUBILA" INTEGER,
  ADD COLUMN IF NOT EXISTS "ID_ROL_RETENCIONES" INTEGER;

DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = current_schema() AND table_name = 'USUARIO' AND column_name = 'ROL'
  ) THEN
    UPDATE "USUARIO" AS u
    SET "ID_ROL_JUBILA" = r."ID_ROL_JUBILA"
    FROM "Rol_Jubila" AS r
    WHERE u."ID_ROL_JUBILA" IS NULL
      AND u."JUBILA" = TRUE
      AND r."NOMBRE_ROL" = CASE WHEN u."ROL" = 'ADMIN' THEN 'ADMIN' ELSE 'JUBILA' END;

    UPDATE "USUARIO" AS u
    SET "ID_ROL_RETENCIONES" = r."ID_ROL_RETENCIONES"
    FROM "Rol_Retenciones" AS r
    WHERE u."ID_ROL_RETENCIONES" IS NULL
      AND u."RETENCIONES" = TRUE
      AND r."NOMBRE_ROL" = CASE WHEN u."ROL" = 'ADMIN' THEN 'Administrador' ELSE 'Retenciones' END;
  END IF;
END $$;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'FK_USUARIO_ROL_JUBILA') THEN
    ALTER TABLE "USUARIO" ADD CONSTRAINT "FK_USUARIO_ROL_JUBILA"
      FOREIGN KEY ("ID_ROL_JUBILA") REFERENCES "Rol_Jubila" ("ID_ROL_JUBILA");
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'FK_USUARIO_ROL_RETENCIONES') THEN
    ALTER TABLE "USUARIO" ADD CONSTRAINT "FK_USUARIO_ROL_RETENCIONES"
      FOREIGN KEY ("ID_ROL_RETENCIONES") REFERENCES "Rol_Retenciones" ("ID_ROL_RETENCIONES");
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS "IX_USUARIO_ID_ROL_JUBILA" ON "USUARIO" ("ID_ROL_JUBILA");
CREATE INDEX IF NOT EXISTS "IX_USUARIO_ID_ROL_RETENCIONES" ON "USUARIO" ("ID_ROL_RETENCIONES");

ALTER TABLE "USUARIO" DROP COLUMN IF EXISTS "ROL";
